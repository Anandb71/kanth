import { useEffect, useState } from "react";
import { film, type FilmState } from "../lib/film.ts";
import { Orb } from "./Orb.tsx";

/** Captions, story cards and the closing card for the recorded demo film. Only mounted with ?film. */
export function FilmLayer() {
  const [f, setF] = useState<FilmState>(film.state);
  useEffect(() => {
    document.body.classList.add("film");
    const off = film.on(setF);
    return () => {
      off();
      document.body.classList.remove("film");
    };
  }, []);
  return (
    <>
      <div className={`film-black ${f.black ? "" : "off"}`} />
      {f.caption ? (
        <div className="film-caption" key={`${f.caption.who}-${f.caption.line}`}>
          <span className="who">
            {f.caption.who}
            {f.caption.where ? <span className="where">{f.caption.where}</span> : null}
          </span>
          {f.caption.line}
        </div>
      ) : null}
      {f.story ? (
        <div className="film-story" key={f.story.title}>
          <b>{f.story.title}</b>
          {f.story.body ? <p>{f.story.body}</p> : null}
        </div>
      ) : null}
      {f.end ? (
        <div className="film-end">
          <div className="film-end-inner">
            <Orb live={false} />
            <h2>
              Bulbul V4 Flash, speaking <em style={{ color: "var(--accent)" }}>as</em> someone.
            </h2>
            {f.end.note ? <div className="note">{f.end.note}</div> : null}
            <ul>
              {f.end.lines.map((l) => (
                <li key={l}>{l}</li>
              ))}
            </ul>
            <div className="credit">
              <b>Try it: kanth-nu.vercel.app</b> · github.com/Anandb71/kanth
              <br />
              Simulated conversation, every voice generated by Bulbul · Built with Sarvam AI for the Sarvam Bulbul Build Challenge
            </div>
          </div>
        </div>
      ) : null}
    </>
  );
}
